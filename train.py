if resume:
    checkpoints = sorted(glob.glob(os.path.join(output_dir, "checkpoint-*")),
                         key=lambda p: int(p.rsplit("-", 1)[-1]))
    if checkpoints:
        resume_from = checkpoints[-1]
        log_msg(f"RESUME=1: resuming from '{resume_from}'")
    else:
        log_msg("RESUME=1 but no checkpoint found; starting from scratch.")

