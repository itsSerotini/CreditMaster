#!/usr/bin/env python3
"""
CreditMaster - QLoRA Fine-Tuning Script with Detailed Logging & Metrics
Base Model: Llama 3.1 8B Instruct (4-bit quant) via Unsloth
Target Hardware: NVIDIA RTX 5060 Ti (8GB VRAM)

Features:
 - Comprehensive Logging Callback (Step time, ETA, GPU VRAM peak, train/eval loss)
 - Logs saved to outputs/training.log & outputs/training_summary.json
 - Train/Validation Split (85% / 15%)
 - train_on_responses_only masking (loss computed solely on assistant's response)
 - LoRA adapters + GGUF Quantization (q4_k_m) + Ollama Modelfile creation

v2 (RAG) configuration via environment variables:
 - RUN_NAME        (default "rag_v2")  -> artifacts in $OUTPUT_DIR/$RUN_NAME/ (v1 artifacts stay untouched)
 - DATASET_TRAIN   (default Dataset/rag_v2/train.jsonl, generated by build_dataset.py)
 - DATASET_TEST    (default Dataset/rag_v2/test.jsonl; if missing, a 15% split of DATASET_TRAIN is used)
 - MAX_SEQ_LENGTH  (default 2560 — RAG prompts average ~1450 tokens, max ~2230)
 - BATCH_SIZE / GRAD_ACCUM (default 1 / 8 — same effective batch as v1, fits 8 GB with longer prompts)
 - EPOCHS, EVAL_STEPS (default 2 / 50)
 - SAVE_STEPS (default 25), RESUME=1 (resume from the latest checkpoint in outputs/)
 - MAX_STEPS (smoke test), SKIP_GGUF=1
"""

