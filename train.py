# ------------------------------------------
# VRAM-friendly evaluation.
# Unsloth's prediction_step forces UNSLOTH_RETURN_LOGITS=1 and materialises the full logits
# (seq_len x 128256, cast to fp32 by accelerate): ~1.7 GB extra per ~2.2k-token RAG sample.
# On 8 GB this crashed training at the first evaluation ("CUDA driver error: device not ready",
# step 50). Here the eval loss uses the same path as training (fused CE, no logits).
# ------------------------------------------
def loss_only_prediction_step(model, inputs, prediction_loss_only, ignore_keys=None):
    inputs = trainer._prepare_inputs(inputs)
    os.environ["UNSLOTH_RETURN_LOGITS"] = "0"
    with torch.no_grad(), trainer.compute_loss_context_manager():
        loss = trainer.compute_loss(model, inputs)
    return (loss.mean().detach(), None, None)

trainer.prediction_step = loss_only_prediction_step

class FreeCacheBeforeEval(TrainerCallback):
    """Release cached training VRAM blocks back to the driver before each evaluation."""
    def on_step_end(self, args, state, control, **kwargs):
        if control.should_evaluate:
            import gc
            gc.collect()
            torch.cuda.empty_cache()

trainer.add_callback(FreeCacheBeforeEval())

